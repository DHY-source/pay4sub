async function waitForText(locator, text) {
  const deadline = Date.now() + 12000;
  while (Date.now() < deadline) { if ((await locator.textContent()).includes(text)) return; await new Promise(resolve => setTimeout(resolve, 100)); }
  assert.fail('Missing text: ' + text);
}
async function noOverflow(page, name) {
  const problems = await page.evaluate(() => {
    const result = [];
    if (document.documentElement.scrollWidth > innerWidth + 1) result.push('document');
    for (const dialog of document.querySelectorAll('dialog[open]')) if (dialog.scrollWidth > dialog.clientWidth + 1) result.push(dialog.id);
    return result;
  });
  assert.deepEqual(problems, [], name + ' horizontal overflow');
}
